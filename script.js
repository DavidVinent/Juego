let prota = function (x, y, vel) {
    this.x = x;
    this.y = y;
    this.clau = false;

    this.muerte = function (x, y) {
        let autista = false;
        if (this.x == x && this.y == y) {
            autista = true;
        }
        return autista
    }

    this.dibuixa = function () {
        ctx.drawImage(tilemap,0,32,32,32, this.x, this.y, 50, 50)
    }
    this.text = function () {
        ctx.font = '30px impact'
        ctx.fillStyle = '#555555'
        ctx.fillText("X: " + this.x + " Y: " + this.y, 50, 50)
    }
    this.margenes = function (x, y) {
        let colisio = false;
        if (escenari[y / 50][x / 50] == 0 || escenari[y / 50][x / 50] == 4) {
            colisio = true;

            return colisio;
        }
        return colisio;
    }
    this.logica = function () {
        if (escenari[this.y / 50][this.x / 50] == 3) {
            this.clau = true;
            retras = 15
            alert("VAMOS")
            escenari[this.y / 50][this.x / 50] = 2
        }
        if (escenari[this.y / 50][this.x / 50] == 1) {
            if (this.clau) {
                alert("puto amo")
            } else (alert("cerrado bobi"))
        }
    }
    this.adalt = function () {
        if (!this.margenes(this.x, this.y - 50)) { this.y = this.y - 50 }
        this.logica()

    }
    this.baix = function () {
        if (!this.margenes(this.x, this.y + 50)) { this.y = this.y + 50 }
        this.logica()
    }

    this.dreta = function () {
        if (!this.margenes(this.x + 50, this.y)) { this.x = this.x + 50 }
        this.logica()

    }
    this.esquerra = function () {
        if (!this.margenes(this.x - 50, this.y)) { this.x = this.x - 50 }
        this.logica()
    }
}






let enemic = function (x, y, vel) {
    this.x = x;
    this.y = y;
    this.vel = vel;
    let retras = 0;
    this.retras = retras;

    this.dibuixa = function () {

        ctx.drawImage(imatge1, this.x, this.y, 50, 50)
    }
    this.margenes = function (x, y) {
        let colisio = false;
        if (escenari[y / 50][x / 50] == 0 || escenari[y / 50][x / 50] == 4) {
            colisio = true;

            return colisio;
        }
        return colisio;
    }

    this.mou = function () {
        let hamuerto = sophie.muerte(this.x, this.y)
        if (hamuerto) {
            alert("Que malo eres chaval")
            sophie.x = 200
            sophie.y = 250
        }

        this.retras++;
        if (this.retras == 50) {
            this.retras = 0

            let posicio = Math.floor(Math.random() * 4)
            if (posicio == 0) {
                if (!this.margenes(this.x - 50, this.y))
                    this.x = this.x - 50
            }
            if (posicio == 1) {
                if (!this.margenes(this.x + 50, this.y))
                    this.x = this.x + 50
            }
            if (posicio == 2) {
                if (!this.margenes(this.x, this.y - 50))
                    this.y = this.y - 50
            }
            if (posicio == 3) {
                if (!this.margenes(this.x, this.y + 50))
                    this.y = this.y + 50
            }



        }
    }
}



